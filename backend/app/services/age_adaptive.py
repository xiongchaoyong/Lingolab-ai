_AGE_CEFR_OFFSETS: Dict[str, int] = {
    "儿童":   -5,  # 门槛降低 5 分，同龄人中表现好即可定更高等级
    "青少年": -5,
    "大学生":  0,
    "职场":    0,
    "中老年": -3,  # 适度宽容
}

# 默认值
_DEFAULT_AGE_GROUP = "大学生"


# ============================================================
# 公共接口
# ============================================================

def get_pronunciation_weights(age_group: str, mode: str = "sentence") -> Dict[str, float]:
    """返回发音评测各维度权重

    Args:
        age_group: 儿童 / 青少年 / 大学生 / 职场 / 中老年
        mode: sentence（句子模式） / word（单词模式）

    Returns:
        {"音素准确度": 0.40, "重音位置": 0.15, ...}
    """
    group = age_group if age_group in _PRONUNCIATION_SENTENCE_WEIGHTS else _DEFAULT_AGE_GROUP
    if mode == "word":
        return _PRONUNCIATION_WORD_WEIGHTS[group]
    return _PRONUNCIATION_SENTENCE_WEIGHTS[group]


def get_conversation_ratio(age_group: str) -> Tuple[float, float]:
    """返回对话评分的语音/文本配比

    Returns:
        (pron_weight, text_weight)，如 (0.60, 0.40) 表示语音占 60%
    """
    group = age_group if age_group in _CONVERSATION_PRON_TEXT_RATIO else _DEFAULT_AGE_GROUP
    return _CONVERSATION_PRON_TEXT_RATIO[group]


def get_conversation_text_weights(age_group: str) -> Dict[str, float]:
    """返回对话评分文本三维权重

    Returns:
        {"语法正确率": 0.40, "词汇丰富度": 0.35, "对话参与度": 0.25}
    """
    group = age_group if age_group in _CONVERSATION_TEXT_WEIGHTS else _DEFAULT_AGE_GROUP
    return _CONVERSATION_TEXT_WEIGHTS[group]


def get_roleplay_role_weights(age_group: str) -> Dict[str, float]:
    """返回角色扮演四维权重

    Returns:
        {"角色贴合度": 0.40, "场景礼仪": 0.25, "专业术语": 0.20, "应对能力": 0.15}
    """
    group = age_group if age_group in _ROLEPLAY_ROLE_WEIGHTS else _DEFAULT_AGE_GROUP
    return _ROLEPLAY_ROLE_WEIGHTS[group]


def get_age_context_for_prompt(age_group: str) -> str:
    """返回注入 LLM 评分 prompt 的年龄段上下文描述"""
    group = age_group if age_group in _AGE_CONTEXT_PROMPTS else _DEFAULT_AGE_GROUP
    return _AGE_CONTEXT_PROMPTS[group]


def get_assessment_age_offset(age_group: str) -> int:
    """返回测评 CEFR 定级的年龄偏移量（正数=更严格，负数=更宽容）"""
    group = age_group if age_group in _AGE_CEFR_OFFSETS else _DEFAULT_AGE_GROUP
    return _AGE_CEFR_OFFSETS[group]
